/** ห่อข้อความผู้ใช้ด้วยตัวคั่น เพื่อแยก "ข้อมูล" ออกจาก "คำสั่ง" ให้ชัดเจน */
export function buildUserPrompt(text: string): string {
  return [
    'ปรับข้อความระหว่างตัวคั่นด้านล่างนี้',
    '',
    '<<<ข้อความต้นฉบับ',
    text,
    'ข้อความต้นฉบับ>>>',
  ].join('\n');
}
